fn pal(parts: &[P]) -> Vec<(char, u32)> {
    parts.iter().flat_map(|p| p.iter().copied()).collect()
}

fn plain(head: &[&str], later: &[&str], parts: &[P], o: Opt) -> Hero {
    make_plain_with(head, later, &pal(parts), o)
}

fn saiyan(head: &[&str], parts: &[P], o: Opt) -> Hero {
    make_hero_opt(head, &pal(parts), o)
}

